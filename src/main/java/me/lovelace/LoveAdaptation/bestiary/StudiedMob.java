    StudiedMob(EntityType type, MobFamily family, String name, String subTitle,
               String stage1Note, String stage2Note, String stage3Note, String stage4Note) {
        this.type = type;
        this.family = family;
        this.name = name;
        this.subTitle = subTitle;
        this.stage1Note = stage1Note;
        this.stage2Note = stage2Note;
        this.stage3Note = stage3Note;
        this.stage4Note = stage4Note;
    }

    public EntityType getType() {
        return type;
    }

    public MobFamily getFamily() {
        return family;
    }

    public String getName() {
        return name;
    }

    public String getSubTitle() {
        return subTitle;
    }

    /**
     * Возвращает отображаемый подвид в зависимости от статуса открытия семейства (открыто только при убийстве 2+ видов семейства).
     */
    public String getDisplaySubTitle(int kills, boolean familyDiscovered) {
        if (!familyDiscovered || kills <= 0) {
            return null;
        }
        return this.subTitle;
    }

    /**
     * Формирует заголовок исследовательской стадии.
     */
    public String getStageHeader(int kills) {
        if (kills <= 0) return "Особь не исследована:";
        if (kills < 5) return "Полевая запись (I):";
        if (kills < 20) return "Полевые наброски (II):";
        if (kills < 50) return "Повадки и среда (III):";
        return "Анатомический анализ (IV):";
    }

    /**
     * Возвращает текст заметки для текущего количества убийств.
     */
    public String getStageContent(int kills) {
        if (kills <= 0) return "Информация отсутствует. Проведите полевые наблюдения в бою.";
        if (kills < 5) return stage1Note;
        if (kills < 20) return stage2Note;
        if (kills < 50) return stage3Note;
        return stage4Note;
    }

    /**
     * Возвращает краткий статус исследования.
     */
    public String getStageStatus(int kills) {
        if (kills <= 0) return "§8[Не исследовано]";
        if (kills < 5) return "§8[Первичный контакт]";
        if (kills < 20) return "§8[Сбор набросков]";
        if (kills < 50) return "§8[Изучение повадок]";
        return "§2✔ Анатомия изучена";
    }

    /**
     * Формирует динамический текст исследовательской заметки на основе количества убийств конкретного вида.
     */
    public String getResearchNote(int kills) {
        if (kills <= 0) {
            return "§8[Информация отсутствует. Особь не исследована]";
        }
        if (kills < 5) {
            return "§4Полевая запись (I):\n§0" + stage1Note;
        }
        if (kills < 20) {
            return "§4Полевые наброски (II):\n§0" + stage2Note;
        }
        if (kills < 50) {
            return "§4Повадки и среда (III):\n§0" + stage3Note;
        }
        return "§4Анатомический анализ (IV):\n§0" + stage4Note;
    }

    public static StudiedMob fromEntityType(EntityType type) {
        if (type == null) return null;
        for (StudiedMob mob : values()) {
            if (mob.type == type) {
                return mob;
            }
        }
        return null;
    }
